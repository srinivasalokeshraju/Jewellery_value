// Bundles plugin/skills/ into src/skills.generated.ts: each skill's MCP entry, with digests, and its files by URI.
// Run it after a change under plugin/skills/. test/tools/skills.test.ts fails while the committed file is stale.
import { skillEntry } from "@modelcontextprotocol/server/ext/skills";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SERVER = fileURLToPath(new URL("..", import.meta.url));
const SKILLS = fileURLToPath(new URL("../../plugin/skills/", import.meta.url));
export const SKILLS_MODULE = "src/skills.generated.ts";

/** Every file under `dir`, as `/`-separated paths relative to it. Only markdown: the module carries files as text. */
async function skillFiles(dir: string): Promise<Record<string, string>> {
  const files: Record<string, string> = {};
  for (const entry of await readdir(dir, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile()) continue;
    const path = `${entry.parentPath}/${entry.name}`.slice(dir.length + 1);
    if (!path.endsWith(".md")) throw new Error(`plugin/skills may hold only markdown files: ${path}`);
    files[path] = await readFile(`${dir}/${path}`, "utf8");
  }
  return files;
}

export async function buildSkillsModule(): Promise<string> {
  const names = (await readdir(SKILLS, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted();
  const entries = [];
  const files: Record<string, string> = {};
  for (const name of names) {
    const own = await skillFiles(`${SKILLS}${name}`);
    entries.push(await skillEntry(name, own));
    for (const path of Object.keys(own).toSorted()) files[`skill://${name}/${path}`] = own[path]!;
  }
  return [
    "// Generated by `npm run skills:build` from plugin/skills/. Do not edit.",
    'import type { Skill } from "@modelcontextprotocol/server/ext/skills";',
    "",
    `export const SKILL_ENTRIES: readonly Skill[] = ${JSON.stringify(entries, null, 2)};`,
    "",
    `export const SKILL_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const module = await buildSkillsModule();
  await writeFile(`${SERVER}${SKILLS_MODULE}`, module);
  console.log(`Wrote ${SKILLS_MODULE}, ${module.length} bytes.`);
}

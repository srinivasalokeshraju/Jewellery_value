// Bundles src/ui/view/ into src/ui/shell.generated.ts, the card document as two strings around the template slot.
// Run it after a change under src/ui/view/. test/ui/shell.test.ts fails while the committed file is stale.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SERVER = fileURLToPath(new URL("..", import.meta.url));
const VIEW = "src/ui/view/";
export const SHELL_MODULE = "src/ui/shell.generated.ts";

/** The view may bundle only its own files and the ext-apps package, which carries its own copies of its dependencies. */
const ALLOWED_INPUTS = [VIEW, "node_modules/@modelcontextprotocol/ext-apps/"];

function fillSlot(frame: string, slot: string, text: string): string {
  const parts = frame.split(slot);
  if (parts.length !== 2) throw new Error(`shell.html must hold ${slot} exactly once.`);
  return parts[0] + text + parts[1];
}

export async function buildShellModule(): Promise<string> {
  const bundled = await build({
    absWorkingDir: SERVER,
    entryPoints: [`${VIEW}main.ts`],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    sourcemap: false,
    write: false,
    metafile: true,
    logLevel: "silent",
  });
  for (const input of Object.keys(bundled.metafile.inputs)) {
    if (!ALLOWED_INPUTS.some((prefix) => input.startsWith(prefix))) {
      throw new Error(`The view may not import ${input}. It may import only ${VIEW}, @modelcontextprotocol/ext-apps, and types.`);
    }
  }
  const js = bundled.outputFiles[0]!.text.trimEnd();
  const css = (await readFile(`${SERVER}${VIEW}card.css`, "utf8")).trimEnd();
  const frame = await readFile(`${SERVER}${VIEW}shell.html`, "utf8");

  const banned: [string, RegExp][] = [
    ["card.css", /url\(|@import/i],
    ["shell.html", /\bsrc=|<link/i],
    ["the bundle", /<\/script|<!--/i],
  ];
  for (const [where, pattern] of banned) {
    const text = where === "card.css" ? css : where === "shell.html" ? frame : js;
    const match = pattern.exec(text);
    if (match !== null) throw new Error(`${where} may not hold ${match[0]}.`);
  }

  const filled = fillSlot(fillSlot(frame, "/*CSS*/", css), "/*JS*/", js);
  const [before, after, ...rest] = filled.split("/*TEMPLATE*/");
  if (before === undefined || after === undefined || rest.length > 0) throw new Error("shell.html must hold /*TEMPLATE*/ exactly once.");
  return [
    "// Generated by `npm run ui:build` from src/ui/view/. Do not edit.",
    `export const SHELL = { before: ${JSON.stringify(before)}, after: ${JSON.stringify(after)} } as const;`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const module = await buildShellModule();
  await writeFile(`${SERVER}${SHELL_MODULE}`, module);
  console.log(`Wrote ${SHELL_MODULE}, ${module.length} bytes.`);
}
